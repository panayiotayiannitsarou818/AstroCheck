# Προαιρετικό πρόθεμα τίτλου: αρίθμηση, markdown ή «Ενότητα Χ:».
_HEADING_PREFIX = (
    r"(?:#{1,3}\s*|\d{1,2}[.)]\s*|[IVX]{1,4}[.)]\s*|(?:Ενότητα|Section)\s+\S{1,3}\s*[:.–-]\s*)?"
)


def _section_heading_re(section: str):
    return re.compile(
        rf"(?im)^\s*{_HEADING_PREFIX}(?:\*\*)?(?:{_SECTION_SYNONYMS[section]})(?:\*\*)?\s*[:.]?\s*$"
    )


def _has_section(text: str, section: str) -> bool:
    """Υπάρχει η ενότητα; Αρχικός τίτλος οπουδήποτε ή συνώνυμο ως τίτλος."""
    if re.search(_SECTION_PATTERNS[section], text, re.IGNORECASE):
        return True
    return bool(_section_heading_re(section).search(text))


def _find_appendix(text: str) -> str:
    """Το κείμενο του Παραρτήματος, από τον ΤΙΤΛΟ του (τελευταίος τίτλος
    Παραρτήματος στο έγγραφο) και μετά. Αν δεν βρεθεί τίτλος, ισχύει η
    παλαιότερη συμπεριφορά (πρώτη εμφάνιση της λέξης «Παράρτημα»)."""
    heading = None
    for m in re.finditer(_SECTION_PATTERNS["Παράρτημα επιβεβαιωμένων όψεων"], text, re.IGNORECASE):
        heading = m
    if heading is None:
        for m in _section_heading_re("Παράρτημα επιβεβαιωμένων όψεων").finditer(text):
            heading = m
    if heading is not None:
        return text[heading.start() :]
    found = [i for i in (text.find("Παράρτημα"), text.find("Appendix")) if i != -1]
    return text[min(found) :] if found else ""


def _normalize_prime_marks(text: str) -> str:
    """Κανονικοποιεί το πρόχειρο ' (ASCII apostrophe, U+0027) και το
    τυπογραφικό ' (right single quote, U+2019) σε ′ (πραγματικό σύμβολο
    πρώτου λεπτού τόξου, U+2032) όταν ακολουθεί ψηφίο -- π.χ. "3°30'" ή
    "3°30'" γίνονται "3°30′".

    Γιατί χρειάζεται: κάθε aspect.orb_text (astrology.orb_to_text) και
    κάθε _NAME_FORMS/regex σε αυτό το module χρησιμοποιεί αποκλειστικά το
    ′. Ένα Word που παράγεται από μοντέλο (ή περνάει από αυτόματο smart-
    quote του Word/ChatGPT) μπορεί να γράψει το πρόχειρο απόστροφο αντ'
    αυτού. Χωρίς αυτή την κανονικοποίηση, το ίδιο ακριβώς, σωστό orb
    χαρακτηρίζεται ψευδώς "ύποπτο/απόν" επειδή η αναζήτηση συμβολοσειράς
    (`orb_text in window`, `re.escape(orb_text)` κ.λπ.) απαιτεί ΑΚΡΙΒΩΣ
    το χαρακτήρα ′. Καλείται μία φορά, στην είσοδο κάθε δημόσιας
    validate_*() συνάρτησης -- όλες οι εσωτερικές κλήσεις (per-house
    τμήματα, Παράρτημα κ.λπ.) προέρχονται από ήδη κανονικοποιημένο κείμενο.
    """
    return re.sub(r"(?<=\d)['’]", "′", text)


def _name_pattern(name: str) -> str:
    return _NAME_FORMS.get(name, re.escape(name))
