"""
validator.py
=============
Ελέγχει το ΤΕΛΙΚΟ κείμενο ανάλυσης (πριν γίνει Word) ενάντια στο ελεγμένο
Chart -- δεν εμπιστεύεται ότι το μοντέλο ακολούθησε τις οδηγίες, το
επαληθεύει μηχανικά. Αυτό είναι το ίδιο ακριβώς λάθος που παρατηρήθηκε
χειροκίνητα (παρέλειψη όψεων παρά τις ρητές οδηγίες) -- ο σκοπός αυτού του
module είναι να μην ξαναπεράσει αθόρυβα.

v2: δύο προσθήκες, ύστερα από δύο συγκεκριμένα περιστατικά που η v1 δεν θα
είχε πιάσει:
  1. Ο μηχανικός έλεγχος κάλυπτε μόνο "Τετράγωνο"/"Αντίθεση". Μια σύνοδος με
     τον Ωροσκόπο ή το Μεσουράνημα (π.χ. Χείρωνας–Ωροσκόπος) δεν ελεγχόταν
     καθόλου, άρα η απουσία της δεν θα εμφανιζόταν ποτέ ως σφάλμα. Τώρα ο
     ορισμός του "mandatory" περιλαμβάνει και κάθε σύνοδο όπου συμμετέχει
     γωνία (astrology.OPPOSITE_ANGLE).
  2. Ο παλιός έλεγχος co-occurrence δεχόταν μια όψη ως "καλυμμένη" αν
     εμφανιζόταν ΟΠΟΥΔΗΠΟΤΕ στο κείμενο -- π.χ. μια όψη του κυβερνήτη ενός
     Οίκου που αναφέρεται μόνο στον Οίκο όπου φυσικά βρίσκεται ο πλανήτης,
     αλλά ποτέ στον Οίκο που ο ίδιος πλανήτης κυβερνά, περνούσε ως OK. Τώρα
     γίνεται ξεχωριστός έλεγχος ανά Οίκο (κανόνας 6Β): κάθε mandatory όψη
     πρέπει να εμφανίζεται μέσα στο τμήμα κειμένου κάθε Οίκου όπου το σημείο
     της είναι "involved" -- Οίκος-κατοικίας ΚΑΙ κάθε Οίκος που κυβερνά.

v3: νέος έλεγχος, ύστερα από συγκεκριμένο περιστατικό (ΠΑΝΑΓΙΩΤΑ, 9ος Οίκος)
που κανένας από τους παραπάνω ελέγχους δεν θα είχε πιάσει: το πλαίσιο
σύνοψης ("Κυβερνήτης: ...") ενός Οίκου είχε αντιγραφεί αυτούσιο από άλλον
Οίκο, ενώ το κυρίως κείμενο του ίδιου Οίκου ονόμαζε σωστά διαφορετικό
πλανήτη ως κυβερνήτη. Ούτε ο έλεγχος όψεων ούτε ο έλεγχος ενοτήτων το
εντοπίζουν, γιατί το λάθος όνομα είναι έγκυρο αστρολογικό όνομα, απλώς για
λάθος Οίκο. Τώρα, για κάθε Οίκο, εξάγεται ο κυβερνήτης (ή οι κυβερνήτες,
όταν δηλώνονται και σύγχρονος και παραδοσιακός) από την εισαγωγική πρόταση
του κυρίως κειμένου, και ελέγχεται ότι το ίδιο όνομα εμφανίζεται μέσα στη
γραμμή "Κυβερνήτης:" του πλαισίου σύνοψης του ΙΔΙΟΥ Οίκου.

v4: τρία κενά από εξωτερική αξιολόγηση με σκόπιμες αλλοιώσεις
(test_reviewer_mutations.py):
  1. Ο κυβερνήτης ελέγχεται πλέον απέναντι στο ζώδιο της ακμής του
     πραγματικού χάρτη (RULERS), σε κείμενο ΚΑΙ πλαίσιο. Ο έλεγχος v3
     σύγκρινε μόνο κείμενο με πλαίσιο, άρα ο ίδιος λάθος πλανήτης και στα
     δύο περνούσε.
  2. Η απουσία ή κενή γραμμή «Κυβερνήτης:» στο πλαίσιο σύνοψης είναι σφάλμα.
  3. Ζεύγος «Α–Β <τύπος>» που δεν υπάρχει στις ελεγμένες όψεις -> σφάλμα.
Επίσης, οι σύνοδοι με γωνία που υπολογίζει η Python (λείπουν από τον
πίνακα Astrodienst) είναι υποχρεωτικές ανά Οίκο όπως και του πίνακα.

v5: δεύτερος γύρος εξωτερικής αξιολόγησης:
  1. Επινοημένες όψεις αναγνωρίζονται και σε φυσικές προτάσεις, ελληνικά και
     αγγλικά («Ο Ήλιος σχηματίζει τετράγωνο με τη Σελήνη», «το τετράγωνο του
     Ήλιου με τη Σελήνη», «The Sun forms a square with the Moon»). Κάθε ρητή
     δήλωση είναι σφάλμα, με ή χωρίς orb. Αρνήσεις και αμφίσημο υποκείμενο
     αγνοούνται σκόπιμα.
  2. Ο κυβερνήτης ελέγχεται και ως ΡΟΛΟΣ: ο «κύριος» πρέπει να είναι ο
     σύγχρονος και ο «παραδοσιακός» ο παραδοσιακός κυβερνήτης της ακμής.

v6: τρίτος γύρος εξωτερικής αξιολόγησης:
  1. Γραμμές πίνακα («Ήλιος–Σελήνη | Τετράγωνο | …», η μορφή του Παραρτήματος
     και του docx_text) ελέγχονται για επινοημένες όψεις.
  2. Η άρνηση μετρά μόνο μέσα στην ίδια πρόταση-δήλωση: στο «Δεν είναι
     εύκολο, επειδή ο Ήλιος σχηματίζει τετράγωνο με τη Σελήνη» η όψη ελέγχεται.
  Η ίδια επινοημένη όψη δοκιμάζεται σε 16 μορφές (πίνακας, πρόταση, σύνταξη)
  και 10 σωστές προτάσεις/γραμμές ελέγχονται ότι γίνονται δεκτές.

v7: τέταρτος γύρος εξωτερικής αξιολόγησης -- από «έλεγχος παρουσίας του
σωστού» σε «έλεγχος κάθε δήλωσης»:
  1. Ενιαίος εξαγωγέας δηλώσεων όψης (validation_aspects._aspect_claims):
     κάθε δήλωση, σε πρόζα ή πίνακα, για γνωστό ή άγνωστο ζεύγος,
     συγκρίνεται ως ζεύγος -> τύπος -> orb -> βαρύτητα. Μια πρόσθετη
     λανθασμένη δήλωση δεν «καλύπτεται» πλέον από μια σωστή αλλού.
  2. Το πλαίσιο σύνοψης πρέπει να δηλώνει ΟΛΟΥΣ τους κυβερνήτες της ακμής.
  3. parser: έλεγχος ΠΛΗΡΟΤΗΤΑΣ του πίνακα όψεων -- πλήθος συμβόλων στο PDF
     ίσο με πλήθος όψεων που διαβάστηκαν (ακριβής ισότητα και στα 6 fixtures).
  Συστηματικός πίνακας tests: γλώσσα × μορφή × είδος λάθους (test_claim_matrix.py).

v8: πέμπτος γύρος εξωτερικής αξιολόγησης:
  1. Δηλώσεις με επίθετο πριν από τον τύπο («ισχυρό τετράγωνο», «a strong
     square») αναγνωρίζονται.
  2. ΟΛΑ τα δηλωμένα orb/βαρύτητες μιας δήλωσης ή γραμμής ελέγχονται· δύο
     αντιφατικές τιμές δεν αλληλοαναιρούνται. Δεκαδικό orb («0.01°») με ανοχή 1′.
  3. Το κυρίως κείμενο κάθε Οίκου πρέπει να ονομάζει κάθε κυβερνήτη ως
     κυβερνήτη (ελαστική σύνταξη)· στο πλαίσιο, ο σύγχρονος πρώτος (Odigies §3).
  4. parser: κάθε κελί του πίνακα όψεων το πολύ μία όψη.

v9 (μαζί με Odigies v6): ΔΟΜΗΜΕΝΗ ΜΟΡΦΗ αντί για αναγνώριση κάθε
διατύπωσης. Μετά από έξι γύρους, κάθε νέα λέξη ή σημείο στίξης χρειαζόταν
νέο μοτίβο. Τώρα:
  1. Κάθε όψη με αριθμούς γράφεται ΜΟΝΟ ως δομημένη γραμμή
     «Α–Β Τύπος (orb X°YY′, Κατηγορία)» ή γραμμή Παραρτήματος, και
     ελέγχεται αυστηρά. Αριθμός orb οπουδήποτε αλλού απορρίπτεται
     (validation_aspects._stray_technical_values) -- εκτός από θέσεις σε
     ζώδιο και αποστάσεις από ακμή.
  2. Η πρόζα ελέγχεται συμπληρωματικά για ζεύγος/τύπο με ΓΕΝΙΚΗ σύνταξη
     (τύπος όψης ανάμεσα σε δύο σημεία της ίδιας φράσης), όχι με λίστα
     ρημάτων/επιθέτων· αναφορικές προτάσεις και άρνηση ύπαρξης καλύπτονται.
  3. Ο ρόλος κυβερνήτη αναγνωρίζεται από τη λέξη-ρόλο και το πλησιέστερο
     όνομα στην ίδια φράση, σε οποιαδήποτε σειρά λέξεων.
  Ελέγχθηκε σε ρεαλιστικές προτάσεις χωρίς όψη (test_structured_format.py).

v10: έβδομος γύρος -- ολοκλήρωση της βασικής εγγύησης της δομημένης μορφής:
  1. Ό,τι γίνεται δεκτό ως δομημένη γραμμή έχει διαβαστεί ΠΛΗΡΩΣ
     (validation_aspects._classify_row). Γραμμή πίνακα που μοιάζει με όψη
     αλλά έχει άγνωστο/αμφίσημο τεχνικό κελί, δύο τύπους ή ≠2 σημεία -> σφάλμα.
  2. Ο πίνακας βασικών δεδομένων (Odigies §12) με θέσεις σε χωριστά κελιά
     γίνεται δεκτός (πριν απορριπτόταν λανθασμένα).
  3. Κόμμα και άνω-κάτω τελεία δεν αποσυνδέουν όνομα από ρόλο κυβερνήτη·
     η διατύπωση των οδηγιών «Ουρανός — παραδοσιακά Κρόνος» γίνεται δεκτή.
  4. Πρόζα: παρενθετική φράση με κόμματα («Ο Ήλιος, σε τετράγωνο με τη Σελήνη,»).

v11: όγδοος γύρος -- πρώτη φορά εντοπίστηκε ΛΑΝΘΑΣΜΕΝΗ ΑΠΟΡΡΙΨΗ σωστής πρότασης:
  1. Ελλειπτικό υποκείμενο: «Η Σελήνη σχηματίζει τρίγωνο με τον Ερμή και
     τρίγωνο με την Αφροδίτη» -> το δεύτερο τρίγωνο αποδίδεται στη Σελήνη
     (πριν: στον Ερμή, δηλαδή ψευδές σφάλμα). Αν το υποκείμενο είναι
     αμφίσημο, ΚΑΜΙΑ δήλωση -- αβεβαιότητα, όχι βέβαιο σφάλμα.
  2. Ίδιο σημείο δύο φορές («Ήλιος–Ήλιος») -> σφάλμα.
  3. Ετικέτες κελιών («Ζεύγος:», «Όψη:», «Orb:») διαβάζονται· η εξαίρεση
     θέσης δεν καλύπτει ποτέ γραμμή με τύπο όψης ή «orb».
  4. Ρόλος κυβερνήτη και μέσα σε παρένθεση («Ο Κρόνος (κύριος κυβερνήτης)»).
  Συνδυαστικές παραλλαγές: κάθε μορφή δοκιμάζεται ΚΑΙ σωστή ΚΑΙ λανθασμένη.

v12: ένατος γύρος:
  1. Το υποκείμενο ενημερώνεται σε κάθε νέα ρητή δήλωση: στο «…, η Αφροδίτη
     σχηματίζει τετράγωνο με τον Άρη και τετράγωνο με τον Κρόνο» το δεύτερο
     τετράγωνο ανήκει στην Αφροδίτη (πριν: στη Σελήνη -> ψευδές σφάλμα).
  2. Πολλά αντικείμενα με κοινό τύπο: «τρίγωνο με τον Ερμή και τον Ήλιο».
     Το «και ο/η …» (νέο υποκείμενο) δεν διαβάζεται ως αντικείμενο.
  3. Αυτοόψη («ο Ήλιος … με τον Ήλιο») απορρίπτεται σε κάθε μορφή.

v13 (τελευταίος γύρος πριν το feature freeze):
  «και με τον», «καθώς και», επεξηγηματική συνέχεια («στον γενέθλιο χάρτη»,
  «in the natal chart»). Το «, με τον …» με σκέτο κόμμα θεωρείται αμφίσημο.

ΟΡΙΟ ΤΟΥ ΕΛΕΓΧΟΥ (σκόπιμο): η ΑΥΣΤΗΡΗ εγγύηση αφορά τις δομημένες γραμμές
όψεων και τους πίνακες (κάθε αριθμός διαβάζεται και συγκρίνεται, αλλιώς
σφάλμα). Η πρόζα ελέγχεται ΣΥΜΠΛΗΡΩΜΑΤΙΚΑ· δεν διεκδικεί πλήρη κάλυψη
ελεύθερης σύνταξης. Σε αμφισημία προτιμάται να μη βγει σφάλμα παρά να
μπλοκαριστεί σωστό κείμενο. Νέες διορθώσεις μόνο από πραγματικά παραδοτέα.

Η λήψη του τελικού Word πρέπει να παραμένει κλειδωμένη όσο
ValidationResult.ok είναι False.
"""

# Ο κώδικας του validator χωρίστηκε σε μικρότερα αρχεία, ανά θέμα:
#   validation_patterns.py   -- μοτίβα κειμένου, τίτλοι Οίκων/ενοτήτων
#   validation_aspects.py    -- έλεγχος όψεων (τύπος, orb, βαρύτητα)
#   validation_structure.py  -- Οίκοι, κυβερνήτες, τοποθετήσεις, προσωπικά
#   validation_analysis.py   -- validate_analysis (τεχνική ανάλυση)
#   validation_rewrite.py    -- validate_rewrite (έντυπο πελάτη)
# Αυτό το αρχείο παραμένει το μοναδικό σημείο εισόδου: «import validator»
# και «from validator import ...» λειτουργούν ακριβώς όπως πριν, μαζί με
# τα εσωτερικά ονόματα (π.χ. validator._has_section) που χρησιμοποιούν τα tests.
import validation_patterns as _patterns
import validation_aspects as _aspects
import validation_structure as _structure
import validation_analysis as _analysis
import validation_rewrite as _rewrite

for _module in (_patterns, _aspects, _structure, _analysis, _rewrite):
    globals().update({k: v for k, v in vars(_module).items() if not k.startswith("__")})
del _module
