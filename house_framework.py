# Το ίδιο πλαίσιο, πιο αναλυτικά, υπάρχει από την έκδοση 7 μέσα στις ενσωματωμένες
# οδηγίες (Odigies_v6.docx, ενότητα 2Α) και στη Δεσμευτική Εντολή. Όταν υπάρχει
# εκεί, ΔΕΝ προστίθεται δεύτερη φορά στην εντολή δημιουργίας (μόνο ο έλεγχος ΤΝ
# χρησιμοποιεί πάντα το συμπαγές πλαίσιο αυτού του αρχείου).
_FRAMEWORK_MARKERS = ("Θεματικό πλαίσιο και όρια των 12 Οίκων", "Συμπληρωματικό πλαίσιο Οίκων")


def already_in(text: str) -> bool:
    return any(marker in (text or "") for marker in _FRAMEWORK_MARKERS)


def framework_block() -> str:
    """Το πλαίσιο ως κείμενο για τις εντολές προς το μοντέλο."""
    lines = ["ΠΛΑΙΣΙΟ ΕΡΜΗΝΕΙΑΣ ΑΝΑ ΟΙΚΟ (v19 — δεσμευτικό)", COMMON_RULES, ""]
    for h in HOUSES:
        lines.append(
            f"{h.number}ος Οίκος — {h.title}. Θέματα: {h.topics}. Όρια: {h.limits}. "
            f"Κατάλληλο: «{h.good}» Ακατάλληλο: «{h.bad}»"
        )
    return "\n".join(lines)
